// Helper to compute ready-plan price based on page count (1 to 10 pages -> 8M to 18M Toman)
export function calculateReadyPlanPriceByPages(pageCount: number, baseMin = 8000000, baseMax = 18000000): number {
  const clamped = Math.max(1, Math.min(10, pageCount));
  const step = (baseMax - baseMin) / 9;
  return Math.round((baseMin + (clamped - 1) * step) / 100000) * 100000;
}

